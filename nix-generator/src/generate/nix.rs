//! Generate Nix expressions (generated.nix).

use anyhow::Result;
use crate::config::{Fetcher, Package};
use crate::version::VersionInfo;
use super::ResolvedPackage;

/// Generate a Nix expression from resolved packages.
pub fn generate_nix(packages: &[ResolvedPackage]) -> Result<String> {
    let mut output = String::new();

    output.push_str("# This file was generated by gum-nix, please do not modify it manually.\n");
    output.push_str("{\n");

    // Collect required fetchers
    let mut needs_fetch_from_github = false;
    let mut needs_fetchgit = false;
    let mut needs_fetchurl = false;

    for (pkg, _) in packages {
        match &pkg.fetch {
            Fetcher::GitHub { .. } => needs_fetch_from_github = true,
            Fetcher::Git { .. } => needs_fetchgit = true,
            Fetcher::Url { .. } => needs_fetchurl = true,
        }
    }

    // Write function arguments
    let mut args = Vec::new();
    if needs_fetch_from_github { args.push("fetchFromGitHub"); }
    if needs_fetchgit { args.push("fetchgit"); }
    if needs_fetchurl { args.push("fetchurl"); }

    if args.is_empty() {
        args.push("fetchurl");
    }

    output.push_str(&format!("  {},\n", args.join(",\n  ")));
    output.push_str("}:\n{\n");

    // Generate each package
    for (pkg, version_info) in packages {
        generate_package(pkg, version_info, &mut output)?;
    }

    output.push_str("}\n");

    Ok(output)
}

/// Generate a single package's Nix expression.
fn generate_package(
    pkg: &Package,
    version_info: &VersionInfo,
    output: &mut String,
) -> Result<()> {
    output.push_str(&format!("  {} = {{\n", pkg.name));
    output.push_str(&format!("    pname = \"{}\";\n", pkg.name));
    output.push_str(&format!("    version = \"{}\";\n", version_info.version));

    let placeholder_sha = "sha256-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=";

    match &pkg.fetch {
        Fetcher::GitHub { owner, repo } => {
            let rev = version_info.rev.as_deref().unwrap_or(&version_info.version);

            output.push_str("    src = fetchFromGitHub {\n");
            output.push_str(&format!("      owner = \"{}\";\n", owner));
            output.push_str(&format!("      repo = \"{}\";\n", repo));
            output.push_str(&format!("      rev = \"{}\";\n", rev));
            output.push_str(&format!("      sha256 = \"{}\";\n", placeholder_sha));
            output.push_str("    };\n");
        }
        Fetcher::Git { url } => {
            let rev = version_info.rev.as_deref().unwrap_or(&version_info.version);

            output.push_str("    src = fetchgit {\n");
            output.push_str(&format!("      url = \"{}\";\n", url));
            output.push_str(&format!("      rev = \"{}\";\n", rev));
            output.push_str(&format!("      sha256 = \"{}\";\n", placeholder_sha));
            output.push_str("    };\n");
        }
        Fetcher::Url { url } => {
            let fetch_url = crate::fetch::interpolate_url(url, &version_info.version);

            output.push_str("    src = fetchurl {\n");
            output.push_str(&format!("      url = \"{}\";\n", fetch_url));
            output.push_str(&format!("      sha256 = \"{}\";\n", placeholder_sha));
            output.push_str("    };\n");
        }
    }

    // Handle cargo_lock if present
    if !pkg.cargo_lock.is_empty() {
        output.push_str("    cargoLock = {\n");
        for lock_file in &pkg.cargo_lock {
            output.push_str(&format!("      \"{}\" = {{\n", lock_file));
            output.push_str(&format!("        lockFile = ./. + \"/{}\";\n", lock_file));
            output.push_str("        outputHashes = {\n");
            output.push_str("          # TODO: compute outputHashes after prefetch\n");
            output.push_str("        };\n");
            output.push_str("      };\n");
        }
        output.push_str("    };\n");
    }

    output.push_str("  };\n\n");

    Ok(())
}
