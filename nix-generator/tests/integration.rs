//! Integration tests for the nix-generator.

use gum_nix::{Config, Fetcher, VersionSource, VersionInfo, generate_nix, generate_json, check_version};

/// Test that a full config roundtrips through parsing and generation.
#[test]
fn test_full_config_to_nix() {
    let input = r#"
hello = {
    src.manual = "2.12.1"
    fetch.url = "https://ftp.gnu.org/gnu/hello/hello-$ver.tar.gz"
}

mylib = {
    src.manual = "1.0.0"
    fetch.github = "example/mylib"
    cargo_lock = ["Cargo.lock"]
}
"#;

    let config = Config::parse(input).expect("config should parse");
    assert_eq!(config.packages.len(), 2);

    let resolved: Vec<_> = config.packages.iter().map(|pkg| {
        let version = match &pkg.src {
            VersionSource::Manual { version } => version.clone(),
            _ => unreachable!(),
        };
        (pkg.clone(), VersionInfo { version, rev: None })
    }).collect();

    let nix = generate_nix(&resolved).expect("should generate nix");
    assert!(nix.contains("hello"));
    assert!(nix.contains("mylib"));
    assert!(nix.contains("fetchurl"));
    assert!(nix.contains("fetchFromGitHub"));
    assert!(nix.contains("pname = \"hello\""));
    assert!(nix.contains("version = \"2.12.1\""));
    assert!(nix.contains("cargoLock"));

    let json = generate_json(&resolved).expect("should generate json");
    let parsed: serde_json::Value = serde_json::from_str(&json).expect("json should be valid");
    assert!(parsed.get("hello").is_some());
    assert!(parsed.get("mylib").is_some());
    assert_eq!(parsed["hello"]["version"], "2.12.1");
    assert_eq!(parsed["mylib"]["version"], "1.0.0");
}

/// Test URL interpolation in generated Nix.
#[test]
fn test_url_interpolation() {
    let input = r#"
pkg = {
    src.manual = "3.0.0"
    fetch.url = "https://example.com/pkg-$ver.tar.gz"
}
"#;

    let config = Config::parse(input).expect("config should parse");
    let resolved: Vec<_> = config.packages.iter().map(|pkg| {
        (pkg.clone(), VersionInfo { version: "3.0.0".to_string(), rev: None })
    }).collect();

    let nix = generate_nix(&resolved).expect("should generate nix");
    assert!(nix.contains("https://example.com/pkg-3.0.0.tar.gz"));
}

/// Test that invalid config produces errors.
#[test]
fn test_invalid_config_errors() {
    let result = Config::parse(r#"bad = { fetch.url = "https://example.com/pkg.tar.gz" }"#);
    assert!(result.is_err());

    let result = Config::parse(r#"bad = { src.manual = "1.0" }"#);
    assert!(result.is_err());

    let result = Config::parse(r#"bad = { src.manual = "1.0"; fetch.url = "https://example.com"; unknown = "x" }"#);
    assert!(result.is_err());
}

/// Test manual version source.
#[tokio::test]
async fn test_manual_version_source() {
    let input = r#"
pkg = {
    src.manual = "1.2.3"
    fetch.url = "https://example.com/pkg.tar.gz"
}
"#;

    let config = Config::parse(input).expect("config should parse");
    let pkg = &config.packages[0];

    let version_info = check_version(pkg).await.expect("should resolve version");
    assert_eq!(version_info.version, "1.2.3");
    assert!(version_info.rev.is_none());
}

/// Test generated.nix structure.
#[test]
fn test_nix_output_structure() {
    let input = r#"
pkg = {
    src.manual = "1.0"
    fetch.url = "https://example.com/pkg.tar.gz"
}
"#;

    let config = Config::parse(input).expect("config should parse");
    let resolved: Vec<_> = config.packages.iter().map(|pkg| {
        (pkg.clone(), VersionInfo { version: "1.0".to_string(), rev: None })
    }).collect();

    let nix = generate_nix(&resolved).expect("should generate nix");

    assert!(nix.starts_with("# This file was generated by gum-nix"));
    assert!(nix.contains("}:"));
    assert!(nix.contains("pkg = {"));
    assert!(nix.contains("pname = \"pkg\""));
    assert!(nix.contains("version = \"1.0\""));
    assert!(nix.contains("src = fetchurl {"));
    assert!(nix.contains("url = \"https://example.com/pkg.tar.gz\""));
}

/// Test GitHub fetcher generates correct Nix.
#[test]
fn test_github_fetcher_nix() {
    let input = r#"
rustdesk = {
    src.manual = "1.4.2"
    fetch.github = "rustdesk/rustdesk"
}
"#;

    let config = Config::parse(input).expect("config should parse");
    let pkg = &config.packages[0];
    assert!(matches!(pkg.fetch, Fetcher::GitHub { .. }));

    let resolved = vec![(pkg.clone(), VersionInfo { version: "1.4.2".to_string(), rev: Some("1.4.2".to_string()) })];
    let nix = generate_nix(&resolved).expect("should generate nix");

    assert!(nix.contains("fetchFromGitHub"));
    assert!(nix.contains("owner = \"rustdesk\""));
    assert!(nix.contains("repo = \"rustdesk\""));
    assert!(nix.contains("rev = \"1.4.2\""));
}

/// Test git fetcher generates correct Nix.
#[test]
fn test_git_fetcher_nix() {
    let input = r#"
mylib = {
    src.manual = "abc1234"
    fetch.git = "https://git.example.com/repo.git"
    git.branch = "main"
}
"#;

    let config = Config::parse(input).expect("config should parse");
    let pkg = &config.packages[0];
    assert!(matches!(pkg.fetch, Fetcher::Git { .. }));
    assert_eq!(pkg.git_branch, Some("main".to_string()));

    let resolved = vec![(pkg.clone(), VersionInfo { version: "abc1234".to_string(), rev: Some("abc1234def".to_string()) })];
    let nix = generate_nix(&resolved).expect("should generate nix");

    assert!(nix.contains("fetchgit"));
    assert!(nix.contains("url = \"https://git.example.com/repo.git\""));
    assert!(nix.contains("rev = \"abc1234def\""));
}
